/**
 * CPIC Data Source Adapter
 *
 * Loads CPIC (Clinical Pharmacogenetics Implementation Consortium) drug-gene
 * guideline data from a local JSON file built by scripts/build-cpic-subset.py
 * and normalizes results to the NormalizedFinding interface.
 *
 * Data is CC0 public domain. The adapter starts DISABLED in the registry
 * and must be flag-gated until data is verified.
 *
 * JIRA: DNA-841
 */

import type {
  DataSourceAdapter,
  NormalizedFinding,
  SourceConfig,
  EvidenceLevel,
} from "./types";

// ─── CPIC JSON shape (mirrors build-cpic-subset.py output) ───

interface CpicGuideline {
  drug_name: string;
  gene: string;
  guideline_recommendation: string;
  evidence_level: string;
  url: string;
}

// ─── Helpers ───

/**
 * Map CPIC evidence_level strings to our numeric EvidenceLevel.
 * CPIC uses letter grades: A (strongest) through D.
 */
function cpicEvidenceLevel(level: string): EvidenceLevel {
  const normalized = level.trim().toUpperCase();
  if (normalized === "A") return 1;
  if (normalized === "A/B" || normalized === "B") return 2;
  if (normalized === "B/C" || normalized === "C") return 3;
  if (normalized === "C/D" || normalized === "D") return 4;
  return 5;
}

// ─── Data file path ───

const CPIC_DATA_PATH = "/data/databases/cpic_guidelines.json";

// ─── Adapter ───

export class CpicAdapter implements DataSourceAdapter {
  config: SourceConfig;

  private guidelines: CpicGuideline[] = [];
  /** Index: gene name (lowercased) -> guidelines for that gene */
  private geneIndex: Map<string, CpicGuideline[]> = new Map();
  private loaded = false;

  constructor() {
    this.config = {
      id: "cpic",
      name: "Clinical Implementation Guidelines",
      enabled: false,
      category: "pharmacogenomics",
      license: "cc0",
      attribution: "CPIC (CC0 Public Domain)",
      version: "unknown",
      lastUpdated: new Date().toISOString().slice(0, 10),
    };
  }

  /**
   * Initialize by loading the CPIC guidelines JSON file.
   * Gracefully handles the case where the data file has not yet been
   * generated by build-cpic-subset.py — the adapter simply stays
   * unavailable until the file is present.
   */
  async initialize(): Promise<void> {
    try {
      const response = await fetch(CPIC_DATA_PATH);
      if (!response.ok) {
        console.warn(
          `[CpicAdapter] Data file not available (${response.status}). ` +
            `Run scripts/build-cpic-subset.py to generate it.`
        );
        return;
      }

      const data: CpicGuideline[] = await response.json();
      this.guidelines = data;

      // Build gene index for efficient lookup
      for (const entry of data) {
        const geneKey = entry.gene.toLowerCase();
        const existing = this.geneIndex.get(geneKey) || [];
        existing.push(entry);
        this.geneIndex.set(geneKey, existing);
      }

      this.loaded = true;
      this.config.version = `${data.length}-entries`;
      console.info(
        `[CpicAdapter] Loaded ${data.length} CPIC drug-gene guidelines.`
      );
    } catch (err) {
      console.warn(
        `[CpicAdapter] Failed to load CPIC data: ${err instanceof Error ? err.message : String(err)}`
      );
    }
  }

  /**
   * Query CPIC guidelines for the given rsIDs.
   *
   * CPIC data is keyed by gene, not rsID. The rsids parameter is used
   * as a lookup key — callers that pass gene symbols (e.g., "CYP2D6")
   * will get direct matches. For rsID-based lookups, the enrichment
   * engine should map rsIDs to genes before calling this adapter.
   *
   * The adapter checks both exact rsID matches in guideline fields and
   * gene-symbol matches, since CPIC data is inherently gene-centric.
   */
  async query(rsids: string[]): Promise<NormalizedFinding[]> {
    if (rsids.length === 0 || !this.loaded) return [];

    const findings: NormalizedFinding[] = [];

    for (const rsid of rsids) {
      const rsidLower = rsid.toLowerCase();

      // Check if the query key matches a gene name in the index
      const geneMatches = this.geneIndex.get(rsidLower);
      if (geneMatches) {
        for (const guideline of geneMatches) {
          findings.push(this.toNormalizedFinding(rsid, guideline));
        }
      }
    }

    return findings;
  }

  getVersion(): string {
    return this.config.version;
  }

  isAvailable(): boolean {
    return this.loaded;
  }

  // ─── Private helpers ───

  private toNormalizedFinding(
    rsid: string,
    guideline: CpicGuideline
  ): NormalizedFinding {
    const gene = guideline.gene || "unknown";
    return {
      id: `cpic:${rsid}:${gene}:${guideline.drug_name}`,
      source: "cpic",
      category: "pharmacogenomics",
      gene,
      rsid,
      genotype: "", // Set by caller with user variant context
      significance: guideline.guideline_recommendation || "see guideline",
      description: `CPIC guideline for ${guideline.drug_name} and ${gene}: ${guideline.guideline_recommendation || "No recommendation text available."}`,
      evidenceLevel: cpicEvidenceLevel(guideline.evidence_level),
      citations: guideline.url ? [guideline.url] : [],
      metadata: {
        drugName: guideline.drug_name,
        cpicEvidenceLevel: guideline.evidence_level,
        guidelineUrl: guideline.url,
      },
    };
  }
}
